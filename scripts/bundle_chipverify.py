#!/usr/bin/env python3
"""Build reproducible two-file ChipVerify inputs from canonical sources."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ["rtl/p04_dot4.sv", "rtl/p04_simd_dot4.sv", "rtl/p04_requantize.sv"]


def outputs():
    design = "// Generated by scripts/bundle_chipverify.py; edit canonical RTL sources.\n"
    design += "\n".join((ROOT / source).read_text() for source in SOURCES)
    return {"design.sv": design, "testbench.sv": (ROOT / "tb/tb_p04_arithmetic.sv").read_text()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed bundles differ")
    args = parser.parse_args()
    target = ROOT / "sim/chipverify"
    target.mkdir(parents=True, exist_ok=True)
    for name, content in outputs().items():
        path = target / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale bundle: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
        print(f"{path.relative_to(ROOT)} sha256={hashlib.sha256(content.encode()).hexdigest()}")


if __name__ == "__main__":
    main()
