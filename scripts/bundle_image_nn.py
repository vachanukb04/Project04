#!/usr/bin/env python3
"""Generate a self-contained ChipVerify test using real-image learned-filter vectors."""
import argparse,hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
v=json.loads((ROOT/'examples/image_nn/vectors.json').read_text())
jobs=v['jobs'];assert len(jobs)==8 and all(len(j['a_words'])==7 for j in jobs)
template=(ROOT/'tb/tb_p04_image_nn.template.sv').read_text()
body=[]
for i,j in enumerate(jobs):
    body.append(f'        // Image output ({j["output_y"]},{j["output_x"]}), learned channel {j["output_channel"]}')
    for k,word in enumerate(j['a_words']):body.append(f"        host(1,32'd{k*4},32'h{word:08x},0,0);")
    for k,word in enumerate(j['b_words']):body.append(f"        host(1,32'd{128+k*4},32'h{word:08x},0,0);")
    expected=j['expected']&0xffffffff
    body.append(f"        run_job(0,128,256,7,32'h{j['bias']&0xffffffff:08x},0,0);")
    body.append(f"        host(0,256,0,0,32'h{expected:08x});")
    body.append(f'        $display("image_patch={i} expected_acc={j["expected"]} matched");')
tb=template.replace('// @REAL_IMAGE_JOBS@','\n'.join(body))
sources=['rtl/p04_dot4.sv','rtl/p04_scratchpad.sv','rtl/p04_conv_patch_engine.sv','rtl/p04_rgb888_to_int8.sv']
outputs={'tb/tb_p04_image_nn.sv':tb,'sim/chipverify_image/testbench.sv':tb,
    'sim/chipverify_image/design.sv':'// Generated by scripts/bundle_image_nn.py\n'+'\n'.join((ROOT/p).read_text() for p in sources)}
for name,text in outputs.items():
    p=ROOT/name;p.parent.mkdir(parents=True,exist_ok=True)
    if args.check:
        if not p.exists() or p.read_text()!=text:raise SystemExit(f'Stale generated file: {name}')
    else:p.write_text(text)
    print(name,hashlib.sha256(text.encode()).hexdigest())
